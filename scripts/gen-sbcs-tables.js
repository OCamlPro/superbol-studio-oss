/* Generates `src/lsp/cobol_common/text_encoding_tables.ml', the tables that
   `Text_encoding' uses to decode single-byte encodings exactly as VS Code
   does.  VS Code decodes files with (a packaged fork of) iconv-lite, so the
   tables are obtained by decoding every byte with iconv-lite.

   Usage (from the root of the repository, after `npm install'):

     node scripts/gen-sbcs-tables.js > src/lsp/cobol_common/text_encoding_tables.ml

   To support another single-byte encoding, add its VS Code identifier (see
   `TextDocument.encoding' in `@types/vscode') to `encodings' below, and
   regenerate. */

"use strict";

const iconv = require("iconv-lite");
const iconvVersion = require("iconv-lite/package.json").version;

/* VS Code identifiers of the single-byte encodings it supports, in the order
   of `TextDocument.encoding'.  VS Code passes these identifiers to iconv-lite
   as they are (except `ibm866' and `big5', which are not listed here). */
const encodings = [
  "windows1252", "iso88591", "iso88593", "iso885915", "macroman", "cp437",
  "windows1256", "iso88596", "windows1257", "iso88594", "iso885914",
  "windows1250", "iso88592", "cp852", "windows1251", "cp866", "cp1125",
  "iso88595", "koi8r", "koi8u", "iso885913", "windows1253", "iso88597",
  "windows1255", "iso88598", "iso885910", "iso885916", "windows1254",
  "iso88599", "windows1258", "windows874", "iso885911", "koi8ru", "koi8t",
  "cp865", "cp850", "cp857",
];

function upperHalf(encoding) {
  if (!iconv.encodingExists(encoding))
    throw new Error(`iconv-lite does not know encoding ${encoding}`);
  const bytes = Buffer.alloc(256);
  for (let i = 0; i < 256; i++) bytes[i] = i;
  const codepoints = [...iconv.decode(bytes, encoding)].map(c => c.codePointAt(0));
  if (codepoints.length !== 256)
    throw new Error(`${encoding} is not a single-byte encoding`);
  for (let i = 0; i < 128; i++)
    if (codepoints[i] !== i)
      throw new Error(`${encoding} does not map byte ${i} to U+${i.toString(16)}`);
  return codepoints.slice(128);
}

const hex = cp => "0x" + cp.toString(16).toUpperCase().padStart(4, "0");

const out = [];
out.push(`(* Generated by scripts/gen-sbcs-tables.js from iconv-lite ${iconvVersion}: \
do not edit. *)`);
out.push("");
out.push("(** Code points of bytes 0x80 to 0xFF in single-byte encodings, by VS Code");
out.push("    identifier.  Bytes 0x00 to 0x7F are ASCII in all of them.  Undefined");
out.push("    bytes map to U+FFFD, as with iconv-lite. *)");
out.push("let upper_halves: (string * int array) list = [");
for (const encoding of encodings) {
  const cps = upperHalf(encoding);
  out.push(`  "${encoding}", [|`);
  for (let i = 0; i < 128; i += 8)
    out.push("    " + cps.slice(i, i + 8).map(hex).join("; ") + ";");
  out.push("  |];");
}
out.push("]");
process.stdout.write(out.join("\n") + "\n");
